CREATE TABLE IF NOT EXISTS public.finance_family_profiles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.finance_workspaces(id) ON DELETE RESTRICT,
  display_name text NOT NULL CHECK (length(btrim(display_name)) BETWEEN 1 AND 80),
  relationship text NOT NULL CHECK (relationship IN ('principal','conjuge','filho','outro')),
  linked_user_id bigint REFERENCES public.finance_users(id) ON DELETE RESTRICT,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (workspace_id, id),
  UNIQUE (workspace_id, linked_user_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS finance_family_one_principal
ON public.finance_family_profiles(workspace_id) WHERE relationship = 'principal';

-- A ausência de registro nesta tabela é interpretada pelo backend como "privado".
-- Ter vínculo como beneficiário, pagador ou titular NÃO implica visibilidade.
CREATE TABLE IF NOT EXISTS public.finance_family_visibility (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.finance_workspaces(id) ON DELETE RESTRICT,
  resource_type text NOT NULL CHECK (resource_type IN ('registro','provisao','conta','transacao')),
  resource_id bigint NOT NULL CHECK (resource_id > 0),
  creator_user_id bigint NOT NULL REFERENCES public.finance_users(id) ON DELETE RESTRICT,
  label text NOT NULL DEFAULT 'privado'
    CHECK (label IN ('privado','casal','familia','selecionados')),
  changed_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (workspace_id, resource_type, resource_id),
  UNIQUE (id, workspace_id)
);

CREATE TABLE IF NOT EXISTS public.finance_family_visibility_grants (
  visibility_id bigint NOT NULL,
  workspace_id uuid NOT NULL,
  user_id bigint NOT NULL REFERENCES public.finance_users(id) ON DELETE RESTRICT,
  granted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (visibility_id,user_id),
  FOREIGN KEY (visibility_id,workspace_id)
    REFERENCES public.finance_family_visibility(id,workspace_id) ON DELETE CASCADE
);

-- Beneficiário do gasto; jamais deve ser usado como ACL.
CREATE TABLE IF NOT EXISTS public.finance_family_cost_allocations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL,
  movement_id bigint NOT NULL REFERENCES public.finance_movements(id) ON DELETE RESTRICT,
  profile_id bigint NOT NULL,
  amount numeric(15,2) NOT NULL CHECK (amount > 0),
  FOREIGN KEY (workspace_id,profile_id)
    REFERENCES public.finance_family_profiles(workspace_id,id) ON DELETE RESTRICT,
  UNIQUE(workspace_id,movement_id,profile_id)
);

-- Quem pagou; não cria um segundo gasto e não credita o beneficiário.
CREATE TABLE IF NOT EXISTS public.finance_family_payment_allocations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL,
  movement_id bigint NOT NULL REFERENCES public.finance_movements(id) ON DELETE RESTRICT,
  payer_profile_id bigint NOT NULL,
  source_account_id bigint REFERENCES public.finance_bank_accounts(id) ON DELETE RESTRICT,
  amount numeric(15,2) NOT NULL CHECK (amount > 0),
  FOREIGN KEY (workspace_id,payer_profile_id)
    REFERENCES public.finance_family_profiles(workspace_id,id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.finance_family_visibility_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.finance_workspaces(id) ON DELETE RESTRICT,
  visibility_id bigint NOT NULL,
  actor_user_id bigint NOT NULL REFERENCES public.finance_users(id) ON DELETE RESTRICT,
  prior_label text, next_label text NOT NULL,
  changed_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (visibility_id,workspace_id)
    REFERENCES public.finance_family_visibility(id,workspace_id) ON DELETE RESTRICT
);

-- Nenhum novo dado da família pode ser consultado pelo anon/authenticated
-- diretamente: acessos são validados no backend depois de sessão + ACL.
ALTER TABLE public.finance_family_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finance_family_visibility ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finance_family_visibility_grants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finance_family_cost_allocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finance_family_payment_allocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finance_family_visibility_audit ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.finance_family_profiles,
  public.finance_family_visibility,
  public.finance_family_visibility_grants,
  public.finance_family_cost_allocations,
  public.finance_family_payment_allocations,
  public.finance_family_visibility_audit FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.finance_family_profiles,
  public.finance_family_visibility,
  public.finance_family_visibility_grants,
  public.finance_family_cost_allocations,
  public.finance_family_payment_allocations,
