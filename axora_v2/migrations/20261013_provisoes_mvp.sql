-- AXORA · Provisões MVP (fase de homologação).
-- Não limpa, altera nem substitui dados financeiros existentes.
-- Execute somente no Supabase autorizado, após backup.
-- API utiliza exclusivamente service_role, nunca anon/authenticated.
BEGIN;

CREATE TABLE IF NOT EXISTS public.finance_provision_rules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description text NOT NULL CHECK (length(btrim(description)) BETWEEN 1 AND 240),
  category text NOT NULL CHECK (length(btrim(category)) BETWEEN 1 AND 120),
  responsible text NOT NULL CHECK (length(btrim(responsible)) BETWEEN 1 AND 120),
  start_due_date date NOT NULL,
  planned_value numeric(14,2) NOT NULL CHECK (planned_value > 0),
  value_mode text NOT NULL CHECK (value_mode IN ('fixed','variable')),
  recurrence text NOT NULL CHECK (recurrence IN ('once','unlimited','until_date','installments')),
  frequency text NOT NULL DEFAULT 'monthly' CHECK (frequency IN ('weekly','biweekly','monthly','bimonthly','quarterly','semiannual','yearly')),
  end_date date,
  installment_count integer,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (recurrence <> 'until_date' OR (end_date IS NOT NULL AND end_date >= start_due_date)),
  CHECK (recurrence <> 'installments' OR (installment_count IS NOT NULL AND installment_count BETWEEN 1 AND 360))
);
CREATE TABLE IF NOT EXISTS public.finance_provision_occurrences (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_id bigint NOT NULL REFERENCES public.finance_provision_rules(id) ON DELETE RESTRICT,
  sequence_no integer NOT NULL CHECK (sequence_no > 0),
  due_date date NOT NULL,
  planned_value numeric(14,2) NOT NULL CHECK (planned_value > 0),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','paid')),
  payment_date date,
  paid_value numeric(14,2),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT finance_provision_occurrences_unique UNIQUE (rule_id,sequence_no),
  CHECK (status = 'open' OR (payment_date IS NOT NULL AND paid_value > 0))
);
ALTER TABLE public.finance_movements
  ADD COLUMN IF NOT EXISTS provision_occurrence_id bigint
  REFERENCES public.finance_provision_occurrences(id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX IF NOT EXISTS finance_movements_provision_once
  ON public.finance_movements(provision_occurrence_id)
  WHERE provision_occurrence_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS finance_provisions_due_status
  ON public.finance_provision_occurrences(status,due_date);

-- Renovação sob demanda: gera até a janela solicitada sem nunca duplicar
-- vencimentos. O dia original é preservado/clampado ao fim do mês.
CREATE OR REPLACE FUNCTION public.axora_ensure_provisions(p_through date DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE v_added integer; v_until date := coalesce(p_through, current_date+interval '18 months');
BEGIN
  IF v_until > current_date + interval '30 months' THEN
    RAISE EXCEPTION 'Janela de geração excede 30 meses';
  END IF;
  WITH calculated AS (
    SELECT r.id, gs.i+1 AS seq,
      CASE WHEN r.frequency='weekly' THEN r.start_due_date + (gs.i*7)
           WHEN r.frequency='biweekly' THEN r.start_due_date + (gs.i*14)
           ELSE (
             date_trunc('month',r.start_due_date)::date
             + (gs.i * CASE r.frequency WHEN 'monthly' THEN 1
                   WHEN 'bimonthly' THEN 2 WHEN 'quarterly' THEN 3
                   WHEN 'semiannual' THEN 6 ELSE 12 END) * interval '1 month'
             + (
                least(extract(day FROM r.start_due_date)::int,
                extract(day FROM (
                   date_trunc('month',r.start_due_date)::date
                   + ((gs.i * CASE r.frequency WHEN 'monthly' THEN 1
                      WHEN 'bimonthly' THEN 2 WHEN 'quarterly' THEN 3
                      WHEN 'semiannual' THEN 6 ELSE 12 END) + 1) * interval '1 month'
                   - interval '1 day'))::int
                ) - 1
               ) * interval '1 day'
           )::date END AS due_date,
      r.planned_value, r.recurrence, r.end_date, r.installment_count
    FROM public.finance_provision_rules r
    CROSS JOIN LATERAL generate_series(
      0,
      least(10000,greatest(0,ceil((v_until-r.start_due_date)::numeric/7)::int + 1))
    ) AS gs(i)
    WHERE r.active
  )
  INSERT INTO public.finance_provision_occurrences(rule_id,sequence_no,due_date,planned_value)
  SELECT id,seq,due_date,planned_value FROM calculated
  WHERE due_date <= v_until
    AND (recurrence <> 'once' OR seq=1)
    AND (recurrence <> 'until_date' OR due_date <= end_date)
    AND (recurrence <> 'installments' OR seq <= installment_count)
  ON CONFLICT (rule_id,sequence_no) DO NOTHING;
  GET DIAGNOSTICS v_added = ROW_COUNT;
  RETURN v_added;
END;
$$;

-- Cadastro de recorrência + geração inicial em uma única transação.
CREATE OR REPLACE FUNCTION public.axora_create_provision(
  p_description text,p_category text,p_responsible text,
  p_start_due_date date,p_planned_value numeric,p_value_mode text,
  p_recurrence text,p_frequency text,p_end_date date DEFAULT NULL,
  p_installment_count integer DEFAULT NULL
) RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $
DECLARE v_id bigint;
BEGIN
  INSERT INTO public.finance_provision_rules(
    description,category,responsible,start_due_date,planned_value,
    value_mode,recurrence,frequency,end_date,installment_count
  ) VALUES (
    p_description,p_category,p_responsible,p_start_due_date,p_planned_value,
    p_value_mode,p_recurrence,p_frequency,p_end_date,p_installment_count
  ) RETURNING id INTO v_id;
  PERFORM public.axora_ensure_provisions();
  RETURN v_id;
END;
$;

-- Uma operação atômica: apenas um pagamento completo e um Registro.
-- Tentativas duplicadas falham antes de inserir uma nova movimentação.
CREATE OR REPLACE FUNCTION public.axora_pay_provision(
  p_occurrence_id bigint, p_payment_date date, p_amount numeric
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE o record; v_movement_id bigint;
BEGIN
  IF p_payment_date IS NULL OR p_amount IS NULL OR p_amount <= 0 OR p_amount > 1000000000000 THEN
    RAISE EXCEPTION 'Pagamento inválido';
  END IF;
  SELECT i.id,i.status,i.due_date,r.description,r.category,r.value_mode
    INTO o
  FROM public.finance_provision_occurrences i
  JOIN public.finance_provision_rules r ON r.id=i.rule_id
  WHERE i.id=p_occurrence_id FOR UPDATE OF i;
  IF NOT FOUND THEN RAISE EXCEPTION 'Provisão não encontrada'; END IF;
  IF o.status <> 'open' THEN RAISE EXCEPTION 'Provisão já quitada'; END IF;
  INSERT INTO public.finance_movements(
    movement_date,description,value,category,competence,classification,
    allocation_value,fixed_variable,provision_occurrence_id
  ) VALUES (
    p_payment_date,o.description,p_amount,o.category,
    to_char(p_payment_date,'MM/YYYY'),'SAÍDA',0,
    CASE WHEN o.value_mode='fixed' THEN 'FIXO' ELSE 'VARIÁVEL' END,
    p_occurrence_id
  ) RETURNING id INTO v_movement_id;
  UPDATE public.finance_provision_occurrences
    SET status='paid',payment_date=p_payment_date,paid_value=p_amount
    WHERE id=p_occurrence_id;
  RETURN jsonb_build_object('occurrence_id',p_occurrence_id,'movement_id',v_movement_id,'status','paid');
END;
$$;

ALTER TABLE public.finance_provision_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finance_provision_occurrences ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.finance_provision_rules,public.finance_provision_occurrences FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.finance_provision_rules,public.finance_provision_occurrences TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.finance_provision_rules_id_seq,public.finance_provision_occurrences_id_seq TO service_role;
REVOKE ALL ON FUNCTION public.axora_create_provision(text,text,text,date,numeric,text,text,text,date,integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.axora_create_provision(text,text,text,date,numeric,text,text,text,date,integer) TO service_role;
REVOKE ALL ON FUNCTION public.axora_ensure_provisions(date) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.axora_pay_provision(bigint,date,numeric) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.axora_ensure_provisions(date) TO service_role;
GRANT EXECUTE ON FUNCTION public.axora_pay_provision(bigint,date,numeric) TO service_role;
COMMIT;
