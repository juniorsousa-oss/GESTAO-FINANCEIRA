-- AXORA BETA: tipos personalizáveis, saldo investido e transferências internas.
-- Exclusivo ao schema axora_beta; outros aplicativos e a produção não são alterados.
BEGIN;
ALTER TABLE axora_beta.finance_bank_accounts
  ADD COLUMN IF NOT EXISTS investment_balance numeric(15,2)
  CHECK (investment_balance IS NULL OR investment_balance >= 0);
ALTER TABLE axora_beta.finance_bank_accounts
  DROP CONSTRAINT IF EXISTS finance_bank_accounts_account_type_check;
ALTER TABLE axora_beta.finance_bank_accounts
  ADD CONSTRAINT finance_bank_accounts_account_type_check
  CHECK (account_type ~ '^[a-z][a-z0-9_-]{1,63}$');

CREATE TABLE IF NOT EXISTS axora_beta.finance_bank_account_types (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES axora_beta.finance_workspaces(id) ON DELETE RESTRICT,
  code text NOT NULL CHECK (code ~ '^[a-z][a-z0-9_-]{1,63}$'),
  label text NOT NULL CHECK (length(btrim(label)) BETWEEN 2 AND 60 AND label = btrim(label)),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (workspace_id, code)
);
CREATE UNIQUE INDEX IF NOT EXISTS axora_bank_type_label_unique
 ON axora_beta.finance_bank_account_types (workspace_id, lower(label));
ALTER TABLE axora_beta.finance_bank_account_types ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE axora_beta.finance_bank_account_types FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON axora_beta.finance_bank_account_types TO service_role;
GRANT USAGE, SELECT ON SEQUENCE axora_beta.finance_bank_account_types_id_seq TO service_role;

INSERT INTO axora_beta.finance_bank_account_types (workspace_id,code,label)
SELECT w.id,t.code,t.label FROM axora_beta.finance_workspaces w
CROSS JOIN (VALUES ('corrente','Conta corrente'),('poupanca','Poupança'),
 ('pagamento','Conta de pagamento'),('outro','Outro')) AS t(code,label)
ON CONFLICT (workspace_id,code) DO NOTHING;

ALTER TABLE axora_beta.finance_bank_accounts
  ADD CONSTRAINT axora_bank_account_type_workspace_fk
  FOREIGN KEY (workspace_id,account_type)
  REFERENCES axora_beta.finance_bank_account_types(workspace_id,code)
  ON UPDATE RESTRICT ON DELETE RESTRICT NOT VALID;
ALTER TABLE axora_beta.finance_bank_accounts VALIDATE CONSTRAINT axora_bank_account_type_workspace_fk;

CREATE OR REPLACE FUNCTION axora_beta.axora_ensure_bank_account_types(p_workspace_id uuid)
RETURNS integer LANGUAGE plpgsql SECURITY INVOKER
SET search_path=axora_beta,pg_temp AS $$
DECLARE n integer;
BEGIN
  INSERT INTO finance_bank_account_types (workspace_id,code,label)
  VALUES (p_workspace_id,'corrente','Conta corrente'),(p_workspace_id,'poupanca','Poupança'),
         (p_workspace_id,'pagamento','Conta de pagamento'),(p_workspace_id,'outro','Outro')
  ON CONFLICT (workspace_id,code) DO NOTHING;
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;
REVOKE ALL ON FUNCTION axora_beta.axora_ensure_bank_account_types(uuid) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION axora_beta.axora_ensure_bank_account_types(uuid) TO service_role;

CREATE TABLE IF NOT EXISTS axora_beta.finance_balance_transfers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES axora_beta.finance_workspaces(id) ON DELETE RESTRICT,
  from_account_id bigint NOT NULL,
  to_account_id bigint NOT NULL,
  amount numeric(15,2) NOT NULL CHECK(amount>0),
  note text CHECK(note IS NULL OR length(note)<=250),
  actor_user_id bigint NOT NULL REFERENCES axora_beta.finance_users(id) ON DELETE RESTRICT,
  request_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT axora_transfer_distinct_accounts CHECK (from_account_id<>to_account_id),
  CONSTRAINT axora_transfer_from_fk FOREIGN KEY(from_account_id,workspace_id)
    REFERENCES axora_beta.finance_bank_accounts(id,workspace_id) ON DELETE RESTRICT,
  CONSTRAINT axora_transfer_to_fk FOREIGN KEY(to_account_id,workspace_id)
    REFERENCES axora_beta.finance_bank_accounts(id,workspace_id) ON DELETE RESTRICT,
  UNIQUE(workspace_id,request_id)
);
CREATE INDEX IF NOT EXISTS axora_transfers_workspace_recent
 ON axora_beta.finance_balance_transfers(workspace_id,created_at DESC,id DESC);
ALTER TABLE axora_beta.finance_balance_transfers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE axora_beta.finance_balance_transfers FROM PUBLIC,anon,authenticated;
GRANT SELECT, INSERT ON axora_beta.finance_balance_transfers TO service_role;
GRANT USAGE,SELECT ON SEQUENCE axora_beta.finance_balance_transfers_id_seq TO service_role;

CREATE OR REPLACE FUNCTION axora_beta.axora_transfer_manual_balance(
 p_workspace_id uuid,p_actor_user_id bigint,p_from_account_id bigint,
 p_to_account_id bigint,p_amount numeric,p_note text,p_request_id uuid
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path=axora_beta,pg_temp AS $$
DECLARE
 from_balance numeric(15,2);
 to_balance numeric(15,2);
 transfer_id bigint;
 old_transfer record;
BEGIN
 IF p_workspace_id IS NULL OR p_actor_user_id IS NULL OR
    p_request_id IS NULL OR p_from_account_id IS NULL OR p_to_account_id IS NULL OR
    p_from_account_id = p_to_account_id THEN
   RAISE EXCEPTION 'Selecione duas contas diferentes.' USING ERRCODE='22023';
 END IF;
 IF p_amount IS NULL OR p_amount <= 0 OR p_amount > 999999999999.99 OR
    p_amount <> round(p_amount,2) THEN
   RAISE EXCEPTION 'Valor inválido: informe um valor positivo com até duas casas decimais.' USING ERRCODE='22023';
 END IF;
 IF p_note IS NOT NULL AND length(btrim(p_note))>250 THEN
   RAISE EXCEPTION 'Observação excede 250 caracteres.' USING ERRCODE='22023';
 END IF;
 IF NOT EXISTS (SELECT 1 FROM finance_users WHERE id=p_actor_user_id) THEN
   RAISE EXCEPTION 'Usuário não encontrado.' USING ERRCODE='22023';
 END IF;
 -- Bloqueia em ordem estável; as duas contas são alteradas na MESMA transação.
 PERFORM id FROM finance_bank_accounts WHERE workspace_id=p_workspace_id
   AND id IN (p_from_account_id,p_to_account_id)
   ORDER BY id FOR UPDATE;
 IF (SELECT count(*) FROM finance_bank_accounts WHERE workspace_id=p_workspace_id
     AND id IN (p_from_account_id,p_to_account_id))<>2 THEN
   RAISE EXCEPTION 'Conta de origem ou destino não pertence a este espaço.' USING ERRCODE='22023';
 END IF;
 SELECT * INTO old_transfer FROM finance_balance_transfers
 WHERE workspace_id=p_workspace_id AND request_id=p_request_id LIMIT 1;
 IF FOUND THEN
   RETURN jsonb_build_object('id',old_transfer.id,'already_applied',true);
 END IF;
 SELECT manual_balance INTO from_balance FROM finance_bank_accounts
 WHERE workspace_id=p_workspace_id AND id=p_from_account_id;
 SELECT manual_balance INTO to_balance FROM finance_bank_accounts
 WHERE workspace_id=p_workspace_id AND id=p_to_account_id;
 IF from_balance IS NULL OR to_balance IS NULL THEN
   RAISE EXCEPTION 'Informe o saldo manual das duas contas antes de transferir.' USING ERRCODE='22023';
 END IF;
 IF from_balance < p_amount THEN
   RAISE EXCEPTION 'Saldo disponível insuficiente na conta de origem.' USING ERRCODE='22023';
 END IF;
 IF to_balance + p_amount > 999999999999.99 THEN
   RAISE EXCEPTION 'Saldo de destino excederia o limite permitido.' USING ERRCODE='22023';
 END IF;
 UPDATE finance_bank_accounts SET manual_balance=manual_balance-p_amount
  WHERE workspace_id=p_workspace_id AND id=p_from_account_id;
 UPDATE finance_bank_accounts SET manual_balance=manual_balance+p_amount
  WHERE workspace_id=p_workspace_id AND id=p_to_account_id;
 INSERT INTO finance_balance_transfers
 (workspace_id,from_account_id,to_account_id,amount,note,actor_user_id,request_id)
 VALUES (p_workspace_id,p_from_account_id,p_to_account_id,p_amount,
 NULLIF(btrim(coalesce(p_note,'')),''),p_actor_user_id,p_request_id)
 RETURNING id INTO transfer_id;
 RETURN jsonb_build_object('id',transfer_id,'already_applied',false,
   'from_balance',from_balance-p_amount,'to_balance',to_balance+p_amount);
END $$;
REVOKE ALL ON FUNCTION axora_beta.axora_transfer_manual_balance(uuid,bigint,bigint,bigint,numeric,text,uuid)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION axora_beta.axora_transfer_manual_balance(uuid,bigint,bigint,bigint,numeric,text,uuid)
 TO service_role;
COMMIT;
